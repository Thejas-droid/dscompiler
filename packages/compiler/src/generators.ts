import path from "node:path";
import type { CompilerConfig, GeneratedArtifact, ResolvedTheme, TokenMetadata, TokenNode, TokenType, TokenValue } from "./types.js";
import { cssVariable, formatCssValue, stableStringify } from "./utils.js";

const HEADER = `/* Generated by Design-System Compiler v0.1.0.\n * Do not edit directly.\n */\n`;

export function generateArtifacts(
  tokens: Map<string, TokenNode>,
  themes: Map<string, ResolvedTheme>,
  config: CompilerConfig,
  componentMetadata: unknown[] = []
): { artifacts: GeneratedArtifact[]; metadata: TokenMetadata[] } {
  const prefix = config.css?.prefix ?? "ds";
  const separator = config.css?.separator ?? "-";
  const sorted = [...tokens.values()].sort((a, b) => a.path.localeCompare(b.path));
  const metadata: TokenMetadata[] = sorted.map((token) => {
    const themeValues: Record<string, TokenValue> = {};
    for (const [name, theme] of [...themes.entries()].sort(([a], [b]) => a.localeCompare(b))) {
      const themed = theme.values.get(token.path);
      if (themed !== undefined) themeValues[name] = themed;
    }
    return {
      name: token.path,
      type: token.type,
      value: token.rawValue,
      resolvedValue: token.resolvedValue ?? token.value,
      references: token.references,
      ...(typeof token.rawValue === "string" && /^\{[^}]+\}$/.test(token.rawValue) ? { reference: token.rawValue.slice(1, -1) } : {}),
      cssVariable: cssVariable(token.path, prefix, separator),
      source: token.source,
      ...(token.description ? { description: token.description } : {}),
      ...(token.since ? { since: token.since } : {}),
      ...(token.deprecated !== undefined ? { deprecated: token.deprecated } : {}),
      ...(token.tags?.length ? { tags: token.tags } : {}),
      ...(token.sourceKind ? { sourceKind: token.sourceKind } : {}),
      ...(Object.keys(themeValues).length ? { themes: themeValues } : {})
    };
  });

  const artifacts: GeneratedArtifact[] = [];
  artifacts.push({ path: "tokens.css", content: generateCss(sorted, prefix, separator), kind: "css" });
  if (config.css?.splitByCategory) {
    const groups = groupBy(sorted, (t) => t.path.split(".")[0] ?? "tokens");
    for (const [category, items] of [...groups.entries()].sort(([a], [b]) => a.localeCompare(b))) {
      artifacts.push({ path: path.join("css", `${category}.css`), content: generateCss(items, prefix, separator), kind: "css" });
    }
  }
  for (const [name, theme] of [...themes.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    artifacts.push({ path: path.join("themes", `${name}.css`), content: generateThemeCss(name, theme, sorted, prefix, separator), kind: "css" });
  }
  artifacts.push({ path: "tokens.ts", content: generateTypescript(sorted, prefix, separator), kind: "typescript" });
  artifacts.push({ path: "token-types.d.ts", content: generateTypes(sorted), kind: "typescript" });
  artifacts.push({ path: "token-metadata.json", content: `${stableStringify(metadata)}\n`, kind: "json" });
  artifacts.push({ path: "token-sources.json", content: `${stableStringify(Object.fromEntries(metadata.map((token) => [token.cssVariable, { file: token.source.file, line: token.source.line, path: token.name }]))) }\n`, kind: "json" });
  artifacts.push({ path: "figma-tokens.json", content: `${stableStringify(generateFigmaMetadata(metadata, themes))}\n`, kind: "json" });
  artifacts.push({ path: "ds.tokens.schema.json", content: `${stableStringify(generateAuthoringSchema())}\n`, kind: "schema" });
  if (config.docs?.enabled !== false) {
    artifacts.push({ path: path.join("docs-data", "tokens.json"), content: `${stableStringify(metadata)}\n`, kind: "docs" });
    artifacts.push({ path: path.join("docs-data", "components.json"), content: `${stableStringify(componentMetadata)}\n`, kind: "docs" });
    artifacts.push({ path: path.join("docs-data", "search-index.json"), content: `${stableStringify(generateSearchIndex(metadata, componentMetadata))}\n`, kind: "docs" });
  }
  return { artifacts, metadata };
}

function generateCss(tokens: TokenNode[], prefix: string, separator: string): string {
  const lines = tokens.map((token) => `  ${cssVariable(token.path, prefix, separator)}: ${formatCssValue(token.resolvedValue ?? token.value)};`);
  return `${HEADER}:root {\n${lines.join("\n")}\n}\n`;
}

function generateThemeCss(name: string, theme: ResolvedTheme, baseTokens: TokenNode[], prefix: string, separator: string): string {
  const changes: string[] = [];
  for (const token of baseTokens) {
    const themed = theme.values.get(token.path);
    const base = token.resolvedValue ?? token.value;
    if (themed !== undefined && !deepEqual(themed, base)) changes.push(`  ${cssVariable(token.path, prefix, separator)}: ${formatCssValue(themed)};`);
  }
  const selector = name === "light" ? `:root,\n[data-theme="light"]` : `[data-theme="${name}"]`;
  return `${HEADER}${selector} {\n${changes.join("\n")}\n}\n`;
}

function generateTypescript(tokens: TokenNode[], prefix: string, separator: string): string {
  const tree: Record<string, unknown> = {};
  for (const token of tokens) {
    const parts = token.path.split(".");
    let cursor = tree;
    for (let i = 0; i < parts.length - 1; i++) {
      const part = parts[i] as string;
      if (!cursor[part] || typeof cursor[part] !== "object") cursor[part] = {};
      cursor = cursor[part] as Record<string, unknown>;
    }
    cursor[parts.at(-1) as string] = `var(${cssVariable(token.path, prefix, separator)})`;
  }
  const names = tokens.map((t) => t.path);
  return `${HEADER}export const tokens = ${JSON.stringify(tree, null, 2)} as const;\n\nexport type TokenName = ${names.length ? names.map((n) => JSON.stringify(n)).join(" | ") : "never"};\n\nconst tokenMap: Record<TokenName, string> = {\n${tokens.map((t) => `  ${JSON.stringify(t.path)}: ${JSON.stringify(`var(${cssVariable(t.path, prefix, separator)})`)}`).join(",\n")}\n};\n\nexport function token(name: TokenName): string {\n  return tokenMap[name];\n}\n`;
}

function generateTypes(tokens: TokenNode[]): string {
  const byType = groupBy(tokens, (t) => t.type);
  const names: string[] = [];
  for (const [type, items] of [...byType.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const typeName = `${pascal(type)}Token`;
    names.push(typeName);
    const union = items.map((t) => `  | ${JSON.stringify(t.path)}`).join("\n") || "never";
    names.push("");
    names.push(`export type ${typeName} =\n${union};`);
  }
  names.push("", `export type TokenName = ${[...byType.keys()].sort().map((t) => `${pascal(t)}Token`).join(" | ") || "never"};`);
  return `${HEADER}${names.join("\n")}\n`;
}

function generateSearchIndex(metadata: TokenMetadata[], components: unknown[]): unknown[] {
  const tokenDocs = metadata.map((t) => ({ kind: "token", id: t.name, title: t.name, text: [t.type, t.description, t.cssVariable, ...(t.tags ?? [])].filter(Boolean).join(" ") }));
  const componentDocs = components.map((c) => {
    const r = c as Record<string, unknown>;
    return { kind: "component", id: String(r.name ?? ""), title: String(r.name ?? ""), text: [r.description, ...(Array.isArray(r.tokens) ? r.tokens : [])].filter(Boolean).join(" ") };
  });
  return [...tokenDocs, ...componentDocs].sort((a, b) => a.id.localeCompare(b.id));
}

function generateFigmaMetadata(metadata: TokenMetadata[], themes: Map<string, ResolvedTheme>): unknown {
  return {
    version: 1,
    sourceOfTruth: "code",
    collections: [
      {
        name: "Design System",
        modes: ["base", ...[...themes.keys()].sort()],
        variables: metadata.map((token) => ({
          name: token.name.replace(/\./g, "/"),
          token: token.name,
          type: token.type,
          base: token.resolvedValue,
          modes: Object.fromEntries(Object.entries(token.themes ?? {}).sort(([a], [b]) => a.localeCompare(b)))
        }))
      }
    ]
  };
}

function generateAuthoringSchema(): unknown {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "Design System Compiler token file",
    type: "object",
    additionalProperties: { $ref: "#/$defs/groupOrToken" },
    $defs: {
      groupOrToken: {
        oneOf: [
          { $ref: "#/$defs/token" },
          { type: "object", additionalProperties: { $ref: "#/$defs/groupOrToken" } }
        ]
      },
      token: {
        type: "object",
        required: ["$value", "$type"],
        properties: {
          $type: { enum: ["color", "dimension", "number", "fontFamily", "fontWeight", "fontSize", "lineHeight", "letterSpacing", "duration", "cubicBezier", "shadow", "border", "gradient", "opacity"] },
          $value: {},
          $description: { type: "string" },
          $since: { type: "string" },
          $tags: { type: "array", items: { type: "string" } },
          $deprecated: { oneOf: [{ type: "boolean" }, { type: "object", properties: { message: { type: "string" }, replacement: { type: "string" }, since: { type: "string" } } }] }
        },
        additionalProperties: false
      }
    }
  };
}

function groupBy<T, K>(items: T[], key: (item: T) => K): Map<K, T[]> {
  const out = new Map<K, T[]>();
  for (const item of items) {
    const k = key(item);
    if (!out.has(k)) out.set(k, []);
    out.get(k)?.push(item);
  }
  return out;
}
function pascal(value: string): string { return value.replace(/(^|[-_.\s])(\w)/g, (_m, _p, c: string) => c.toUpperCase()); }
function deepEqual(a: unknown, b: unknown): boolean { return JSON.stringify(a) === JSON.stringify(b); }
